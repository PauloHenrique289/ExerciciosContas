# 1. Soma de dois números inteiros
a = 10
b = 3
print("1. Soma:", a + b )

# 2. Subtração do segundo numero do primeiro
print("2. Subtração:", a - b )

# 3. Multiplicação de dois números
print("3. multiplicação:", a * b ) 

# 4. Divisão com ponto flutuante 
print("4. divisão:", a / b )

# 5. resto da divisão 
print("5. resto:", a % b )

# 6. Media de 3 numeros inteiros
n1, n2, n3, = 7, 8, 9
media = (n1 + n2 + n3) / 3
print("6. media:", media) 

# 7. Quadrado de um número (usando **)
n = 5 
print("7. Quadrado:", n ** 2)

# 8. dobro de um numero qualquer 
print("8. dobro:", n * 2)

# 9. Divisão inteira por 2(usando //)
print ("9. divisão inteira por 2:", n // 2)

