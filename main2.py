# 14. Media ponderada de tres notas (pesos 2, 3 e 5)
print("\n--- 14. media ponderada ---")
nota1 = float(input("digite a nota 1 (peso 2): "))
nota2 = float(input("digite a nota 2 (pesos 3): "))
nota3 = float(input("digite a nota 3 (peso 5): "))
